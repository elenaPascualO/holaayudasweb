"""SEO routes: segmented sitemap (open/closed grants by year).

Sitemaps are served from files pregenerated by services/sitemaps.py. If a
file doesn't exist yet (e.g. first start), it is built on demand in a worker
thread — never on the event loop, since building reads 600K+ rows — and
cached in memory.
"""

import asyncio
import gzip
import logging
import re
from collections.abc import Callable
from datetime import datetime, timezone

from fastapi import APIRouter, Request
from fastapi.responses import Response

from backend.services import sitemaps
from backend.services.cache import TTLCache

router = APIRouter()
logger = logging.getLogger(__name__)

# In-memory cache for the on-demand fallback only (pregenerated files take precedence)
_sitemap_cache = TTLCache(max_size=50)

# Re-exported for the SEO completeness tests
_STATIC_PAGES = sitemaps.STATIC_PAGES

# Cache TTLs (seconds)
_TTL_INDEX = 3600  # 1h
_TTL_STATIC = 86400  # 24h
_TTL_OPEN = 3600  # 1h — grants can change status
_TTL_CLOSED_CURRENT_YEAR = 21600  # 6h — current year still receives closures
_TTL_CLOSED_PAST = 86400  # 24h — historical, stable

# Regex for closed segment: "2025" or "2025-2"
_CLOSED_SEGMENT_RE = re.compile(r"^(\d{4})(?:-(\d+))?$")


def _accepts_gzip(request: Request) -> bool:
    return "gzip" in request.headers.get("accept-encoding", "")


def _xml_response(content: str, cache_max_age: int, request: Request) -> Response:
    """Return an XML response, gzip-compressed only if the client accepts it."""
    headers = {"Cache-Control": f"public, max-age={cache_max_age}"}
    if _accepts_gzip(request):
        headers["Content-Encoding"] = "gzip"
        return Response(
            content=gzip.compress(content.encode("utf-8")),
            media_type="application/xml",
            headers=headers,
        )
    return Response(content=content, media_type="application/xml", headers=headers)


def _gzip_response(data: bytes, cache_max_age: int, request: Request) -> Response:
    """Return already-compressed XML, decompressing only for clients without gzip."""
    headers = {"Cache-Control": f"public, max-age={cache_max_age}"}
    if _accepts_gzip(request):
        headers["Content-Encoding"] = "gzip"
        return Response(content=data, media_type="application/xml", headers=headers)
    return Response(content=gzip.decompress(data), media_type="application/xml", headers=headers)


async def _serve(
    request: Request, filename: str, cache_max_age: int, build: Callable[[], str]
) -> Response:
    """Serve a pregenerated sitemap, or build it in a thread if it doesn't exist yet."""
    data = await asyncio.to_thread(sitemaps.read_sitemap, filename)
    if data is not None:
        return _gzip_response(data, cache_max_age, request)

    xml = _sitemap_cache.get(filename)
    if xml is None:
        logger.info("Sitemap %s not pregenerated — building on demand", filename)
        xml = await asyncio.to_thread(build)
        _sitemap_cache.set(filename, xml, cache_max_age)
    return _xml_response(xml, cache_max_age, request)


def invalidate_sitemap_cache() -> None:
    """Invalidate on-demand fallback caches affected by sync.

    Clears: index, all open-* entries, closed-{current_year}.
    Leaves past-year closed caches untouched (they don't change).
    """
    current_year = str(datetime.now(timezone.utc).year)
    keys_to_remove = [
        key for key in list(_sitemap_cache._store.keys())
        if key == sitemaps.INDEX_FILENAME
        or key.startswith("sitemap-grants-open")
        or key.startswith(f"sitemap-grants-closed-{current_year}")
    ]
    for key in keys_to_remove:
        _sitemap_cache._store.pop(key, None)
    if keys_to_remove:
        logger.info("Invalidated %d sitemap cache entries after sync", len(keys_to_remove))


@router.get("/sitemap.xml")
async def sitemap_index(request: Request) -> Response:
    """Sitemap index listing static + open batches + closed-by-year sitemaps."""
    return await _serve(
        request, sitemaps.INDEX_FILENAME, _TTL_INDEX, lambda: sitemaps.build_index_xml()
    )


@router.get("/sitemap-static.xml")
async def sitemap_static(request: Request) -> Response:
    """Sitemap for static pages."""
    return await _serve(
        request, "sitemap-static.xml", _TTL_STATIC, lambda: sitemaps.build_static_xml()
    )


@router.get("/sitemap-grants-open-{page}.xml")
async def sitemap_grants_open(page: int, request: Request) -> Response:
    """Paginated sitemap for open grant detail pages.

    Args:
        page: 1-indexed page number.
    """
    if page < 1:
        return _xml_response(sitemaps.empty_urlset(), _TTL_STATIC, request)

    return await _serve(
        request,
        f"sitemap-grants-open-{page}.xml",
        _TTL_OPEN,
        lambda: sitemaps.build_open_xml(page),
    )


@router.get("/sitemap-grants-closed-{segment}.xml")
async def sitemap_grants_closed(segment: str, request: Request) -> Response:
    """Sitemap for closed grants of a specific year (with optional overflow page).

    Segment format: "2025" (page 1) or "2025-2" (page 2 of year 2025).
    """
    match = _CLOSED_SEGMENT_RE.match(segment)
    if not match:
        return _xml_response(sitemaps.empty_urlset(), _TTL_STATIC, request)

    year = match.group(1)
    page = int(match.group(2)) if match.group(2) else 1
    if page < 1:
        return _xml_response(sitemaps.empty_urlset(), _TTL_STATIC, request)

    current_year = str(datetime.now(timezone.utc).year)
    ttl = _TTL_CLOSED_CURRENT_YEAR if year == current_year else _TTL_CLOSED_PAST

    return await _serve(
        request,
        f"sitemap-grants-closed-{segment}.xml",
        ttl,
        lambda: sitemaps.build_closed_xml(year, page),
    )
